// 自动分配温和的法名（设计文档 2.1）：游客即可进入，第一次保存功德时再引导登录。
import { randInt } from './util.js';

const SETS = {
  'zh-Hant': {
    a: ['清', '松', '竹', '雲', '月', '石', '溪', '蓮', '靜', '明', '素', '安', '和', '澄', '寧', '若', '遠', '空', '林', '露'],
    b: ['風', '葉', '心', '山', '泉', '影', '光', '禾', '舟', '燈', '雪', '香', '鳴', '水', '谷', '雨', '苔', '音'],
  },
  'zh-Hans': {
    a: ['清', '松', '竹', '云', '月', '石', '溪', '莲', '静', '明', '素', '安', '和', '澄', '宁', '若', '远', '空', '林', '露'],
    b: ['风', '叶', '心', '山', '泉', '影', '光', '禾', '舟', '灯', '雪', '香', '鸣', '水', '谷', '雨', '苔', '音'],
  },
};

export function dharmaName(locale = 'zh-Hant') {
  const s = SETS[locale] || SETS['zh-Hant'];
  const a = s.a[randInt(s.a.length)];
  let b = s.b[randInt(s.b.length)];
  while (b === a) b = s.b[randInt(s.b.length)];
  return randInt(4) === 0 ? `小${a}${b}` : `${a}${b}居士`;
}
